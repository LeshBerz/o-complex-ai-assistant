/**
 * Поиск родовых форм в русском тексте ответа (эвристика). Зона prompt-engineer.
 * Ответ отправляет менеджер, пол которого неизвестен, и пол клиента мы тоже не угадываем.
 * Используют: scripts/eval.ts (ответы модели), data/eval/validate.ts (few-shot и фразы матрицы).
 *
 * Ловит:
 *  - голос отправителя: «рад/рада», «я готова», «я уточнила», «Передала ваш вопрос»;
 *  - обращение к клиенту: «вы уверена», «вы готов», «дорогая Анна», «уважаемый клиент».
 * Не ловит (намеренно): «рады», «радость», «заказ готов», «посылка готова», «упаковка была повреждена»,
 * «вы уверены» (множественное число нейтрально).
 */

const W = "[а-яё]"; // буква
const B = `(?<!${W})`; // левая граница слова (\b не работает с кириллицей)
const E = `(?!${W})`; // правая граница слова

/** Краткие прилагательные и причастия с родом: о себе или о клиенте */
const SHORT_ADJ =
  "(рада?|готова?|уверена?|благодарна|благодарен|признательна|признателен|счастлива?|обязана?|должна|должен|вынуждена?|согласна?|довольна|доволен|права?|записана?|огорчена?|расстроена?)";

/** Глаголы, которыми менеджер обычно говорит о себе, в прошедшем времени */
const SERVICE_PAST =
  "(уточнил|передал|проверил|посмотрел|узнал|записал|оформил|отправил|понял|нашел|нашла|увидел|получил|сообщил|связался|связалась|передала|уточнила|проверила|посмотрела|узнала|записала|оформила|отправила|поняла|увидела|получила|сообщила)а?";

const RULES: { name: string; re: RegExp }[] = [
  // «рад»/«рада» о себе: других значений у слова почти нет, «рады» не совпадёт
  { name: "отправитель: рад/рада", re: new RegExp(`${B}рада?${E}`, "giu") },
  // «я …готова/уверена…» через 0–2 слова
  { name: "отправитель: я + краткое прилагательное", re: new RegExp(`${B}я\\s+(${W}+\\s+){0,2}${SHORT_ADJ}${E}`, "giu") },
  // «я уточнила», «я уже передал», «я не нашла»
  { name: "отправитель: я + прошедшее время", re: new RegExp(`${B}я\\s+(${W}+\\s+){0,2}${W}+(л|ла|лся|лась)${E}`, "giu") },
  // «Уточнила у коллег», «Передал ваш вопрос» в начале фразы без «я»
  { name: "отправитель: глагол прошедшего времени в начале фразы", re: new RegExp(`(^|[.!?…]\\s+|,\\s*)${SERVICE_PAST}${E}`, "giu") },
  // «вы уверена», «вы, конечно, готов», «вам должна»
  { name: "клиент: вы + краткое прилагательное", re: new RegExp(`${B}вы\\s+(${W}+[,]?\\s+){0,2}${SHORT_ADJ}${E}`, "giu") },
  // «дорогая Анна», «уважаемый клиент», «милая»
  // без флага i: имя после обращения отличаем по заглавной букве («дорогой набор» — не обращение)
  {
    name: "клиент: родовое обращение",
    re: new RegExp(`(?<![а-яёА-ЯЁ])([Дд]орог(ая|ой)|[Уу]важаем(ая|ый)|[Мм]ил(ая|ый))\\s+([А-ЯЁ]|клиент|покупател|друг|подруг)`, "gu"),
  },
  { name: "клиент: обращение по полу", re: new RegExp(`${B}(девушка|мужчина|сударыня|сударь)${E}`, "giu") },
];

/** «рада»/«готова» и т.п., у которых слово «я»/«вы» стоит дальше, не считаем: там часто подлежащее — товар */
export function genderedFormHits(text: string): string[] {
  const t = text.replace(/ё/g, "е").replace(/Ё/g, "Е");
  const hits: string[] = [];
  for (const { name, re } of RULES) {
    for (const m of t.matchAll(re)) {
      const at = m.index ?? 0;
      hits.push(`${name}: «${t.slice(at, at + m[0].length).trim()}»`);
    }
  }
  return hits;
}
